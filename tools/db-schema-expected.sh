#!/usr/bin/env bash
# 重新生成 internal/store/schema_expected.go（数据库结构期望清单）。
#
# 只有在**有意修改库结构**（加表/加列/改类型/改索引）之后才需要跑：
#   BF_DB_NAME=bubblefighter_cn0261 BF_DB_USER=root BF_DB_PASSWORD=... \
#     ./tools/db-schema-expected.sh > internal/store/schema_expected.go
#
# 服务端启动时用这份清单做结构体检：清单里的表/列必须存在且类型、可空性、
# 键、自增属性一致；**多出来的表和列不算错**（允许后续平滑加字段）。
# 数据内容（行数/数值）完全不参与校验。
set -euo pipefail

db="${BF_DB_NAME:-bubblefighter_cn0261}"
user="${BF_DB_USER:-root}"
# 默认走本地 socket（Debian 的 root 免密）；要连远端再给 BF_HOST/BF_PORT/BF_DB_PASSWORD。
client=(mariadb -u "$user")
[ -n "${BF_HOST:-}" ] && client+=(-h "$BF_HOST")
[ -n "${BF_PORT:-}" ] && client+=(-P "$BF_PORT")
[ -n "${BF_DB_PASSWORD:-}" ] && client+=(-p"$BF_DB_PASSWORD")

echo "// Code generated by tools/db-schema-expected.sh; DO NOT EDIT."
echo "//"
echo "// expectedSchema is the database structure this build requires: one line per"
echo "// column, \"table|column|type|nullable|key|extra\". CheckSchema compares the live"
echo "// database against it; extra tables/columns are tolerated, missing or changed"
echo "// ones are not. Regenerate after an intentional schema change."
echo "package store"
echo
echo 'const expectedSchema = `'"$("${client[@]}" -N -B -e "
SELECT CONCAT_WS('|', TABLE_NAME, COLUMN_NAME, COLUMN_TYPE, IS_NULLABLE, COLUMN_KEY, EXTRA)
FROM information_schema.columns
WHERE table_schema = '${db}'
ORDER BY TABLE_NAME, ORDINAL_POSITION;")"'`'
